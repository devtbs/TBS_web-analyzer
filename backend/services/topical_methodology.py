MAP_RULES = """
TBS TOPICAL MAP METHOD:
- Establish the source context (actual offering and conversion goal), central entity, and
  central search intent (what the reader wants to do with that entity) before selecting topics.
- Core covers attributes directly supporting that offering. Outer covers relevant supporting
  attributes and must have a natural bridge to Core. Do not invent services the business offers.
- Weigh attribute relevance to the business, prominence in defining the entity, and measured
  popularity separately. Volume alone is not a reason to create a page.
- Each page has one primary entity-attribute focus / macro context. Related subquestions can
  belong on that page. Use observed SERP/query evidence to justify a separate URL; similarity
  is a review signal, not proof of cannibalization. Unknown demand is not zero demand.
- Prefer improving an observed existing URL over proposing a duplicate. Preserve its URL.
  Label each node create or update, its evidence and page-boundary rationale. Do not invent
  ranking positions, search volumes, competitors' rankings, or URLs presented as existing.
- Start with useful, comprehensive quality nodes around the main offering, then deepen their
  supporting clusters. Do not pad the plan to meet a quota or force competitor gap claims.
- Link related parent, child and sibling contexts; Outer should support Core. Anchor meaning
  must match the destination's actual context. Label unverified opportunities as hypotheses.
"""
BRIEF_RULES = """
TBS BRIEF AND WRITING METHOD:
- Keep one macro context answering the title. Define the entity and answer the title early.
- Order H2/H3 headings by user needs and supplied query/competitor evidence, grouping related
  attributes. Distinguish observed headings from suggested additions; never claim research
  was performed when it was not supplied.
- Use roughly 70% main coverage and 30% supplementary context as a flexible guide, not a quota.
  Connect supplementary sections back to the actual offering through natural contextual bridges.
- Specify direct answers immediately after headings, then evidence, examples, useful
  counterpoints and a transition. Avoid repeated sections and forced generic FAQs/conclusions.
- Recommend tables, lists or visuals only where they help explain the topic. Keep link anchors
  aligned with destination meaning; do not invent URLs, statistics, studies or quotations.
- Mark facts needing research as verification tasks in briefs. In articles omit unsupported
  factual specifics instead of fabricating certainty or citations. End with a relevant next step.
"""
